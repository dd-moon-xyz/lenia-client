import math
import time
import errno
import subprocess
from pathlib import Path


class HardwarePWM:
    # RP1 PWM0 channel 2 on GPIO18, using the Linux PWM interface.

    PERIOD_NS = 500_000  # 2 kHz, generated by the peripheral rather than Python.

    def __init__(self, root=Path('/sys/class/pwm'), configure_pin=None):
        chips = [p for p in root.glob('pwmchip*')
                 if p.resolve().parent.parent.name == '1f00098000.pwm']
        if len(chips) != 1:
            raise OSError('RP1 PWM0 controller unavailable; see wiki/wiring/indicator-led.md')
        chip = chips[0]
        self.channel = chip / 'pwm2'
        if not self.channel.exists():
            try:
                (chip / 'export').write_text('2')
            except OSError as error:
                if error.errno != errno.EBUSY:
                    raise
        # udev assigns the gpio group after export.
        for attempt in range(40):
            try:
                self._write('duty_cycle', 0)
                break
            except (FileNotFoundError, PermissionError):
                if attempt == 39:
                    raise
                time.sleep(.025)
        try:
            self._write('enable', 0)
            self._write('period', self.PERIOD_NS)
            self._write('polarity', 'normal')
            if configure_pin is None:
                subprocess.run(['/usr/bin/pinctrl', 'set', '18', 'a3'], check=True,
                               capture_output=True, text=True)
            else:
                configure_pin()
            self._write('enable', 1)
        except BaseException:
            self._write('duty_cycle', 0)
            raise
        self.duty = 0

    def _write(self, name, value):
        (self.channel / name).write_text(str(value))

    def set_brightness(self, value):
        duty = round(min(1.0, max(0.0, value)) * self.PERIOD_NS)
        if duty != self.duty:
            self._write('duty_cycle', duty)
            self.duty = duty

    def close(self):
        # Leave an enabled zero-duty signal: disabled PWM output is undefined.
        self._write('duty_cycle', 0)
        self.duty = 0


class IndicatorLight:
    MIN_BRIGHTNESS = .02
    MAX_BRIGHTNESS = .25
    FADE_SECONDS = 4.0  # Each half of the eight-second idle pulse.
    SENSOR_FADE_SECONDS = 2.0

    def __init__(self, gpio=None, clock=time.monotonic):
        self.gpio = gpio if gpio is not None else HardwarePWM()
        self.clock = clock
        self.fade_started = clock()
        self.brightness = self.fade_brightness = self.MIN_BRIGHTNESS
        self.target = self.MAX_BRIGHTNESS
        self.active = False
        self.gpio.set_brightness(self.brightness)
        print('Indicator ready: GPIO18 / pin 12, 3.3 V hardware PWM at 2 kHz', flush=True)

    def update(self, active, population_fraction=None):
        if population_fraction is not None:
            self.brightness = self.MAX_BRIGHTNESS * min(1.0, max(0.0, population_fraction))
            self.gpio.set_brightness(self.brightness)
            return

        now = self.clock()
        if active != self.active:
            self.fade_started = now
            self.fade_brightness = self.brightness
            self.target = 0.0 if active else self.MAX_BRIGHTNESS
        self.active = active
        if not active:
            # Advance idle half-cycles without drifting with polling delays.
            while now - self.fade_started >= self.FADE_SECONDS:
                self.fade_started += self.FADE_SECONDS
                self.fade_brightness = self.target
                self.target = (self.MIN_BRIGHTNESS if self.target == self.MAX_BRIGHTNESS
                               else self.MAX_BRIGHTNESS)
        duration = self.SENSOR_FADE_SECONDS if active else self.FADE_SECONDS
        progress = min(1.0, max(0.0, (now - self.fade_started) / duration))
        # Sensor fade-out runs twice as fast as an idle half-cycle.
        blend = .5 * (1 - math.cos(math.pi * progress))
        self.brightness = self.fade_brightness + (self.target - self.fade_brightness) * blend
        self.brightness = min(max(self.fade_brightness, self.target),
                              max(min(self.fade_brightness, self.target), self.brightness))
        self.gpio.set_brightness(self.brightness)

    def close(self):
        self.gpio.close()
